-- ============================================================================
-- NovaCart -- Broader version of 16_fix_tile_brand_collisions.sql.
--
-- The same bug (a subcategory-tile product also carrying a real brand name,
-- so it silently wins the byBrand lookup ahead of the correct dedicated
-- brand product) also existed in the ORIGINAL app data from
-- 13_add_gendered_products.sql -- e.g. the "Hoodies" product is also
-- tagged brand = 'Adidas', so clicking the "Adidas" brand tile could open
-- the "Hoodies" product instead of the real Adidas product.
--
-- General rule going forward: a product's `brand` field should only ever
-- be used to satisfy a BRAND tile if that product's job IS to represent
-- that brand (a dedicated brand product, subcategory = null). A product
-- that exists to represent a SUBCATEGORY tile should only be found via
-- bySubcategory, never via byBrand -- so we clear `brand` on every product
-- that has a subcategory set.
--
-- Mobiles is the one deliberate exception: there, the subcategory tile
-- name genuinely IS the brand (e.g. the "iPhone" tile/brand are the same
-- thing), so keeping brand = subcategory there is correct, not a collision.
--
-- Safe to re-run.
-- ============================================================================

update public.products
set brand = null
where subcategory is not null
  and brand is not null
  and category_id not in (select id from public.categories where slug = 'mobiles');


